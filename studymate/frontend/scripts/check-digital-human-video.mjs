import assert from "node:assert/strict"
import { readFileSync, statSync } from "node:fs"
import { resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
const source = (path) => readFileSync(resolve(root, path), "utf8")

const video = source("src/components/DigitalHumanVideo.tsx")
const fallback = source("src/components/DigitalHumanMedia.tsx")
const tutorBubble = source("src/components/TutorBubble.tsx")
const voiceTutor = source("src/pages/VoiceTutor.tsx")
const ttsPipeline = source("src/lib/ttsPipeline.ts")
const mediaConfig = source("src/lib/digitalHuman.ts")
const videoStyles = source("src/components/DigitalHumanVideo.css")

assert.equal([...video.matchAll(/<video/gu)].length, 2, "idle and speaking must use separate video tracks")
assert.match(video, /\bmuted\b/u, "digital-human video must stay muted")
assert.match(video, /\bplaysInline\b/u, "digital-human video must support inline mobile playback")
assert.match(video, /visibilitychange/u, "video must pause when the document is hidden")
assert.match(video, /IntersectionObserver/u, "video must pause when it leaves the viewport")
assert.match(video, /useReducedMotion/u, "reduced-motion must have a static fallback")
assert.match(video, /data-active-track/u, "the active idle/speaking track must be observable")
assert.match(video, /speakingVideo\.currentTime = 0/u, "each real speaking turn must start the talk track naturally")
assert.doesNotMatch(video, /resumeRecentTrack|speakingResumeWindow/u, "a new speaking turn must never resume an older answer")
assert.match(video, /data-active-track=\{speakingTrackVisible \? "speaking" : "idle"\}/u, "active-track must report the visible track")
assert.match(video, /data-idle-resting/u, "idle playback must expose its natural resting phase")
assert.match(video, /onEnded=\{handleIdleEnded\}/u, "idle video must use a controlled non-mechanical cadence")
assert.match(video, /"pre-end"/u, "the primary idle hold path must run before media end")
assert.match(video, /"ended-fallback"/u, "media ended must remain a fallback path")
assert.match(video, /data-idle-boundary-armed/u, "pre-end boundary timers must be observable")
assert.match(video, /data-idle-restart-pending/u, "idle restart timers must be observable")
assert.match(video, /idlePlaybackAllowedRef\.current = false[\s\S]*clearIdleTimers\(\)/u, "hidden or offscreen media must clear idle timers")
assert.match(video, /lastFrameOffsetSeconds/u, "alpha idle must rest on the last decodable frame")
assert.match(video, /speakingTrackVisible \|\| idleTrackVisible/u, "the warm idle track must cover speaking-track startup")
assert.match(mediaConfig, /holdMilliseconds: \[360, 780, 520, 1040\]/u, "idle rest durations must vary")
assert.match(mediaConfig, /preEndLeadSeconds: 0\.08/u, "idle hold must arm before media end")
assert.match(mediaConfig, /lastFrameOffsetSeconds: 0\.04/u, "idle hold must seek to a decodable frame")
assert.match(videoStyles, /opacity 280ms cubic-bezier/u, "track changes need a soft opacity transition")
assert.match(videoStyles, /digital-human-idle-drift 11\.6s/u, "the transparent idle needs a subtle long-period drift")
const voicePlaybackLifecycle = voiceTutor.match(/onPlaybackStart:[\s\S]*?onDrain:[\s\S]*?setVoiceState\("listening"\)/u)?.[0] ?? ""
assert.match(voicePlaybackLifecycle, /onPlaybackStart:[\s\S]*?setVoiceState\("speaking"\)/u, "TTS playback must enter speaking")
assert.doesNotMatch(
  voicePlaybackLifecycle.match(/onPlaybackStart:[\s\S]*?onDrain:/u)?.[0] ?? "",
  /setVoiceState\("listening"\)/u,
  "sentence boundaries inside one pipeline must not leave speaking",
)
assert.match(ttsPipeline, /while \(!this\.cancelled && this\.queue\.length > 0\)[\s\S]*?notifyDrainIfReady\(\)/u, "TTS sentences must drain as one queue")
assert.doesNotMatch(fallback, /AnimatePresence/u, "fallback must not crossfade state pose images")
assert.doesNotMatch(fallback, /studymate-tutor-(listening|thinking|speaking)/u, "fallback must use one honest poster")
assert.match(voiceTutor, /<LecturerAvatar/u, "voice stage must use the continuous lecturer video")
assert.match(voiceTutor, /talking=\{state === "speaking"\}/u, "video speaking mode must follow real playback state")
assert.match(voiceTutor, /准备朗读/u, "TTS synthesis needs a non-speaking preparation label")
assert.match(voiceTutor, /真人讲师视频/u, "voice stage must describe the real lecturer media honestly")
assert.match(tutorBubble, /generating \? "thinking" : "idle"/u, "text generation must not impersonate TTS speaking")
assert.match(tutorBubble, /<DigitalHumanVideo/u, "floating tutor must use the continuous idle video")
assert.match(tutorBubble, /\bidleOnly\b/u, "floating tutor must not preload or impersonate speaking")
assert.match(tutorBubble, /\bfloatingBlend\b/u, "floating tutor video must use the transparent presentation")
assert.match(tutorBubble, /floatingIdleSrc/u, "floating tutor must use the transparent WebM source")
assert.doesNotMatch(tutorBubble, /<DigitalHumanMedia/u, "floating tutor must not use a static full-body image as its main media")
assert.match(tutorBubble, /localStorage\.setItem\(TUTOR_POSITION_KEY/u, "floating position must persist")
assert.match(tutorBubble, /TUTOR_GREETING = "我是你的学习助教，有问题随时来问我。"/u, "floating tutor must introduce itself")
assert.match(tutorBubble, /greetingDue \? 2200 : 75000/u, "the greeting must appear promptly while later hints stay low-frequency")
assert.match(tutorBubble, /localStorage\.setItem\(TUTOR_HIDDEN_KEY/u, "the hidden preference must persist")
assert.match(tutorBubble, /显示 StudyMate 学习助教/u, "a hidden tutor must retain an accessible restore control")
assert.match(mediaConfig, /idleSrc/u, "closed-mouth idle video source must be configured")
assert.match(mediaConfig, /speakingSrc/u, "real speaking video source must be configured separately")
assert.match(mediaConfig, /floatingIdleSrc/u, "transparent floating video source must be configured separately")

const mp4 = statSync(resolve(root, "public/avatars/lecturer_talk.mp4"))
const poster = statSync(resolve(root, "public/avatars/lecturer_talk_poster.jpg"))
const idleMp4 = statSync(resolve(root, "public/digital-human/studymate-lecturer-idle.mp4"))
const idlePoster = statSync(resolve(root, "public/digital-human/studymate-lecturer-idle-poster.jpg"))
const floatingIdleWebm = statSync(resolve(root, "public/digital-human/studymate-tutor-idle-transparent.webm"))
const floatingIdlePoster = statSync(resolve(root, "public/digital-human/studymate-tutor-idle-transparent-poster.png"))
const fullbodyFallback = statSync(resolve(root, "public/digital-human/studymate-tutor-transparent.png"))
assert.ok(mp4.size > 100_000, "continuous video asset is missing or unexpectedly small")
assert.ok(poster.size > 10_000, "video poster asset is missing or unexpectedly small")
assert.ok(idleMp4.size > 20_000, "closed-mouth idle loop is missing or unexpectedly small")
assert.ok(idlePoster.size > 10_000, "closed-mouth idle poster is missing or unexpectedly small")
assert.ok(floatingIdleWebm.size > 10_000, "transparent floating WebM is missing or unexpectedly small")
assert.ok(floatingIdlePoster.size > 50_000, "transparent floating poster is missing or unexpectedly small")
assert.ok(fullbodyFallback.size > 100_000, "transparent full-body fallback is missing or unexpectedly small")

console.log("Digital-human idle/speaking video checks passed.")
